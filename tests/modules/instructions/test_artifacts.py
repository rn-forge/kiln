def test_s4_3_5_property5_root_hygiene_fails_on_a_stray_root_file(
    tmp_path: Path,
) -> None:
    root = _new(tmp_path)
    (root / "NOTES.md").write_text("# Notes\n", encoding="utf-8")
    codes = [f.code for f in INSTRUCTIONS.checks(KilnConfig.load(root), root)]
    assert codes == ["hygiene.stray-root-file"]


def test_s4_3_5_1_edits_to_each_body_survive_and_the_block_is_unchanged(
    tmp_path: Path,
) -> None:
    root = _new(tmp_path)
    for name in ("README.md", "CLAUDE.md", "AGENTS.md"):
        assert (root / name).is_file(), name
    edited: dict[str, str] = {}
    for name in ("README.md", "CLAUDE.md", "AGENTS.md"):
        path = root / name
        text = path.read_text(encoding="utf-8")
        edited[name] = "Hand-written first line.\n\n" + text
        path.write_text(edited[name], encoding="utf-8")

    assert _actions(root, tmp_path)[BLOCK_KEY] is Action.UNCHANGED
    config = KilnConfig.load(root)
    scaffold(root, config)
    cycle.apply(root, home=tmp_path / "home")
    for name, text in edited.items():
        assert (root / name).read_text(encoding="utf-8") == text, name


def test_s4_3_5_2_turning_sonar_off_updates_only_the_block_and_standard(
    tmp_path: Path,
) -> None:
    root = _new(tmp_path, profile="none")
    claude_before = (root / "CLAUDE.md").read_text(encoding="utf-8")
    _write_config(root, profile="none", sonar=False)

    changed = {
        key
        for key, action in _actions(root, tmp_path).items()
        if action not in (Action.UNCHANGED, Action.SKIP)
    }
    # `cicd` owns the Sonar job and properties file, so its two rows move as well.
    assert changed == {
        BLOCK_KEY,
        STANDARD,
        ".github/workflows/ci.yml",
        "sonar-project.properties",
    }

    cycle.apply(root, home=tmp_path / "home")
    claude_after = (root / "CLAUDE.md").read_text(encoding="utf-8")
    assert "Sonar off" in (KILN_BLOCK.extract(claude_after) or "")
    assert "Sonar off" in (root / STANDARD).read_text(encoding="utf-8")
    assert KILN_BLOCK.remove(claude_after) == KILN_BLOCK.remove(claude_before)


def test_s4_3_5_3_a_hand_edit_to_standard_md_is_drift(tmp_path: Path) -> None:
    root = _new(tmp_path)
    standard = root / STANDARD
    standard.write_text(
        standard.read_text(encoding="utf-8") + "\nA note.\n", encoding="utf-8"
    )
    assert _actions(root, tmp_path)[STANDARD] is Action.DRIFT


def test_s4_3_5_4_external_renders_the_url_into_the_block(tmp_path: Path) -> None:
    root = _root(
        tmp_path,
        profile="external",
        docs_extra='external_url = "https://docs.example.com/demo"\n',
    )
    block = _rendered(root)[BLOCK_KEY]
    assert "- **Docs:** external, at <https://docs.example.com/demo>.\n" in block
    assert "Docs rules" not in block


def test_s4_3_5_4_none_renders_no_docs_bullet(tmp_path: Path) -> None:
    block = _rendered(_root(tmp_path, profile="none"))[BLOCK_KEY]
    assert "**Docs:**" not in block
    assert "Docs rules" not in block
    assert "docs:build" not in block


