from rn_forge.kiln.modules.docs.scaffold import scaffold_adr_index
from rn_forge.kiln.modules.instructions.scaffold import (
    scaffold as instructions_scaffold,
)

BLOCK_KEY = "docs/adr/index.md#rn-forge kiln"
RECORD_PAGES = {
    "python-app": ("ARCH-0001", "ARCH-0002"),
    "python-tool": ("ARCH-0001", "ARCH-0002"),
    "python-lib": ("ARCH-0003",),
}
REPO = Path(__file__).resolve().parents[3]


def _root(
    tmp_path: Path, archetype: str = "python-tool", profile: str = "mkdocs"
) -> Path:
    return write_config(
        tmp_path,
        archetype,
        name="demo",
        docs=profile,
        packages=LIB_PACKAGES if archetype == "python-lib" else None,
    )


def _artifacts(root: Path) -> dict[str, object]:
    return {a.key: a for a in DOCS.artifacts(KilnConfig.load(root), root)}


def _new(
    tmp_path: Path,
    archetype: str = "python-tool",
    backend: str | None = None,
    frontend: str | None = None,
) -> Path:
    if backend is None:
        root = _root(tmp_path, archetype)
    else:
        root = write_config(
            tmp_path,
            archetype,
            name="demo",
            docs="mkdocs",
            backend=backend,
            frontend=frontend,
        )
    config = KilnConfig.load(root)
    instructions_scaffold(root, config)
    scaffold_adr_index(root, config)
    cycle.apply(root, home=tmp_path / "home")
    generate.generate(root, config.packages if archetype == "python-lib" else ())
    return root


@pytest.mark.parametrize("archetype", sorted(RECORD_PAGES))
def test_renders_the_records_for_each_python_cell(
    tmp_path: Path, archetype: str
) -> None:
    artifacts = list(
        DOCS.artifacts(KilnConfig.load(_root(tmp_path, archetype)), tmp_path)
    )
    expected = [
        (BLOCK_KEY, ArtifactKind.BLOCK),
        *(
            (f"docs/adr/kiln/{i}.md", ArtifactKind.MANAGED)
            for i in RECORD_PAGES[archetype]
        ),
        ("docs/adr/kiln/index.md", ArtifactKind.MANAGED),
    ]
    tail = [(a.key, a.kind) for a in artifacts][-len(expected) :]
    assert tail == expected
    pages = {a.key: a.content for a in artifacts}
    for record in RECORD_PAGES[archetype]:
        assert pages[f"docs/adr/kiln/{record}.md"].startswith(f"<!-- Generated by kiln")
        assert f"# {record} — " in pages[f"docs/adr/kiln/{record}.md"]
        assert f"[{record}]({record}.md) | " in pages["docs/adr/kiln/index.md"]
    assert pages[BLOCK_KEY].startswith("\n## kiln's architecture baseline\n")


def test_a_scaffolded_index_and_kiln_s_block_plan_as_insert(tmp_path: Path) -> None:
    root = _root(tmp_path)
    scaffold_adr_index(root, KilnConfig.load(root))
    body = (root / "docs/adr/index.md").read_text(encoding="utf-8")
    assert _actions(root, tmp_path)[BLOCK_KEY] is Action.INSERT

    cycle.apply(root, home=tmp_path / "home")
    index = (root / "docs/adr/index.md").read_text(encoding="utf-8")
    assert index.startswith(body)
    assert ADR_BLOCK.extract(index) is not None
    again = _actions(root, tmp_path)
    assert "docs/adr/index.md" not in again
    assert again[BLOCK_KEY] is Action.UNCHANGED


def test_scaffold_adr_index_leaves_an_existing_index_alone(tmp_path: Path) -> None:
    root = _root(tmp_path)
    index = root / "docs/adr/index.md"
    index.parent.mkdir(parents=True)
    index.write_text("Mine.\n", encoding="utf-8")
    scaffold_adr_index(root, KilnConfig.load(root))
    assert index.read_text(encoding="utf-8") == "Mine.\n"


@pytest.mark.parametrize(
    ("archetype", "profile"), [("node-lib", "mkdocs"), ("python-tool", "external")]
)
def test_scaffold_adr_index_does_nothing_without_records(
    tmp_path: Path, archetype: str, profile: str
) -> None:
    root = _root(tmp_path, archetype, profile)
    scaffold_adr_index(root, KilnConfig.load(root))
    assert not (root / "docs").exists()


def test_the_block_survives_an_edit_to_the_seeded_index(tmp_path: Path) -> None:
    root = _new(tmp_path)
    path = root / "docs/adr/index.md"
    before = path.read_text(encoding="utf-8")
    block = ADR_BLOCK.extract(before)
    path.write_text("A line above.\n\n" + before, encoding="utf-8")

    cycle.apply(root, home=tmp_path / "home")
    after = path.read_text(encoding="utf-8")
    assert after.startswith("A line above.\n")
    assert ADR_BLOCK.extract(after) == block


@pytest.mark.parametrize("profile", ["external", "none"])
def test_profiles_other_than_mkdocs_render_no_records(
    tmp_path: Path, profile: str
) -> None:
    root = _root(tmp_path, profile=profile)
    assert [a.key for a in DOCS.artifacts(KilnConfig.load(root), root)] == []


def test_node_lib_renders_no_records_and_no_block(tmp_path: Path) -> None:
    root = _root(tmp_path, "node-lib")
    keys = list(_artifacts(root))
    assert BLOCK_KEY not in keys
    assert not [k for k in keys if k.startswith("docs/adr/kiln/")]


@pytest.mark.parametrize("archetype", sorted(RECORD_PAGES))
def test_the_rendered_files_are_mdformat_clean(tmp_path: Path, archetype: str) -> None:
    root = _new(tmp_path / "repo", archetype)
    out = tmp_path / "out"
    shutil.copytree(root / "docs" / "adr", out / "docs" / "adr")
    (out / ".mdformat.toml").write_text(
        (REPO / ".mdformat.toml").read_text(encoding="utf-8"), encoding="utf-8"
    )
    result = subprocess.run(
        [sys.executable, "-m", "mdformat", "--check", str(out)],
        capture_output=True,
        text=True,
        cwd=out,
    )
    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.parametrize("archetype", sorted(RECORD_PAGES))
def test_docs_checks_pass_with_the_records(tmp_path: Path, archetype: str) -> None:
    root = _new(tmp_path, archetype)
    codes = [f.code for f in module_findings("docs", KilnConfig.load(root), root)]
    assert "docs.orphan-page" not in codes
    assert "docs.broken-link" not in codes


WEB_CELLS = [
    ("python-web-api", "fastapi", None, 3),
    ("python-web-app", "fastapi", "angular", 3),
    ("python-web-api", "django", None, 2),
]


@pytest.mark.parametrize(("archetype", "backend", "frontend", "rows"), WEB_CELLS)
def test_the_web_records_are_mdformat_clean_and_linked(
    tmp_path: Path,
    archetype: str,
    backend: str,
    frontend: str | None,
    rows: int,
) -> None:
    root = _new(tmp_path / "repo", archetype, backend, frontend)
    index = (root / "docs/adr/kiln/index.md").read_text(encoding="utf-8")
    assert sum(line.startswith("| [ARCH-") for line in index.splitlines()) == rows
    out = tmp_path / "out"
    shutil.copytree(root / "docs" / "adr", out / "docs" / "adr")
    (out / ".mdformat.toml").write_text(
        (REPO / ".mdformat.toml").read_text(encoding="utf-8"), encoding="utf-8"
    )
    result = subprocess.run(
        [sys.executable, "-m", "mdformat", "--check", str(out)],
        capture_output=True,
        text=True,
        cwd=out,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    codes = [f.code for f in module_findings("docs", KilnConfig.load(root), root)]
    assert "docs.orphan-page" not in codes
    assert "docs.broken-link" not in codes


def test_a_hand_edit_to_a_record_is_drift(tmp_path: Path) -> None:
    root = _new(tmp_path)
    record = root / "docs/adr/kiln/ARCH-0001.md"
    record.write_text(
        record.read_text(encoding="utf-8").replace("Decision", "Decided", 1),
        encoding="utf-8",
    )
    assert _actions(root, tmp_path)["docs/adr/kiln/ARCH-0001.md"] is Action.DRIFT
