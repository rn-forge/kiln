@pytest.mark.parametrize("archetype", NODE_ARCHETYPES)
def test_s16_7_3_4_every_kiln_owned_file_prettier_parses_is_ignored(
    tmp_path: Path, archetype: str
) -> None:
    root = _root(tmp_path, archetype)
    cycle.apply(root, home=tmp_path / "home")
    state = json.loads((root / ".rn-forge/kiln/state.json").read_text("utf-8"))
    patterns = _patterns(_artifacts(root)[".prettierignore"])
    parsed = [
        path
        for path, entry in state["entries"].items()
        if entry["kind"] == "managed"
        and Path(path).suffix in (".yml", ".yaml", ".json", ".mjs")
    ]

    assert parsed
    assert [p for p in parsed if not _ignored(p, patterns)] == []


def _ignored(path: str, patterns: list[str]) -> bool:
    name = path.rsplit("/", 1)[-1]
    for pattern in patterns:
        if pattern.endswith("/") and path.startswith(pattern):
            return True
        if pattern.startswith("*.") and name.endswith(pattern[1:]):
            return True
        if pattern == path or pattern == name:
            return True
    return False


def _node_tasks(root: Path) -> dict[str, dict]:
    rendered = {a.path: a.content for a in TASKS.artifacts(KilnConfig.load(root), root)}
    return {
        "node": YamlUtils.load(rendered["tasks/node.yml"])["tasks"],
        "root": YamlUtils.load(rendered["Taskfile.yml"])["tasks"],
    }


@pytest.mark.parametrize("archetype", NODE_ARCHETYPES)
def test_s16_7_3_5_tasks(tmp_path: Path, archetype: str) -> None:
    tasks = _node_tasks(_root(tmp_path, archetype))

    assert tasks["node"]["format"]["internal"] is True
    assert tasks["node"]["format"]["cmds"] == ["pnpm exec prettier --write ."]
    assert tasks["node"]["lint:format"]["internal"] is True
    assert tasks["node"]["lint:format"]["cmds"] == ["pnpm exec prettier --check ."]
    lint = [c for c in tasks["root"]["lint"]["cmds"] if c["task"] != "workspace:step"]
    assert lint[lint.index({"task": "node:lint"}) + 1] == {"task": "node:lint:format"}
    fmt = tasks["root"]["format"]["cmds"]
    assert fmt.index({"task": "node:format"}) + 1 == fmt.index(
        {"task": "quality:format:markdown"}
    )
    assert "Prettier formatting" in tasks["root"]["lint"]["desc"]
    assert "Prettier-formatted files" in tasks["root"]["format"]["desc"]
    if archetype == "python-web-app":
        assert fmt.index({"task": "python:format"}) + 1 == fmt.index(
            {"task": "node:format"}
        )


