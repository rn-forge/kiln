def _normalized(text: str) -> str:
    """Drop the provenance line's kiln version, the only line that never matches."""
    return re.sub(
        r"^# Generated by kiln .*$",
        "# Generated by kiln X",
        text,
        count=1,
        flags=re.M,
    )


