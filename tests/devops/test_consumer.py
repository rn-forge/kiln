def _stubs(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """`npm` and `node` on PATH that log `<tool> <cwd-name> <args>`."""
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    log = tmp_path / "calls.log"
    for tool in ("npm", "node"):
        script = bin_dir / tool
        script.write_text(
            "#!/bin/sh\n"
            f'echo "{tool} $(basename "$PWD") $*" >> "{log}"\n'
            'case "$PWD" in *"/$FAIL_CELL") [ "$1" = smoke.mjs ] && exit 1;; esac\n'
            f'if [ "{tool}" = npm ]; then\n'
            '  mkdir -p "node_modules/@rn-forge/ng"\n'
            '  if [ -n "$INSTALLED" ]; then printf \'%s\' "$INSTALLED"; '
            'else echo \'{"exports":{".":{"default":"./a.mjs"}}}\'; fi '
            '> "node_modules/@rn-forge/ng/package.json"\n'
            "fi\n"
        )
        script.chmod(script.stat().st_mode | stat.S_IEXEC)
    monkeypatch.setenv("PATH", f"{bin_dir}:/usr/bin:/bin")
    return log


def _workspace(
    tmp_path: Path, manifest: dict | None = None, tarball: bool = True
) -> None:
    lib = tmp_path / "libs/ng"
    lib.mkdir(parents=True)
    (lib / "package.json").write_text(json.dumps(manifest or _library()))
    tarballs = tmp_path / "dist/tarballs"
    tarballs.mkdir(parents=True)
    if tarball:
        (tarballs / "rn-forge-ng-0.3.0.tgz").write_text("")


def test_s9_4_5_5_each_cell_gets_a_fixture_install_smoke_and_hook(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    log = _stubs(tmp_path, monkeypatch)
    _workspace(tmp_path)
    monkeypatch.chdir(tmp_path)
    assert cli.main(["consumer", "libs/ng"]) == 0
    assert "consumer: 2 cells passed" in capsys.readouterr().out
    base = tmp_path / "dist/consumer-fixtures/rn-forge-ng-0.3.0"
    fixture = json.loads((base / "a-zone/package.json").read_text())
    assert fixture == {
        "name": "consumer-a-zone",
        "private": True,
        "type": "module",
        "dependencies": {
            "rxjs": "~7.9.0",
            "zone.js": "~0.16.0",
            NAME: f"file:{tmp_path / 'dist/tarballs/rn-forge-ng-0.3.0.tgz'}",
        },
    }
    assert 'import "zone.js";' in (base / "a-zone/smoke.mjs").read_text()
    hook = f"{tmp_path}/tools/consumer/ng-smoke.mjs {base}"
    assert log.read_text().splitlines() == [
        "npm a-zone install --no-audit --no-fund",
        "node a-zone smoke.mjs",
        f"node a-zone {hook}/a-zone a-zone",
        "npm b-zoneless install --no-audit --no-fund",
        "node b-zoneless smoke.mjs",
        f"node b-zoneless {hook}/b-zoneless b-zoneless",
    ]


def test_s9_4_5_5_an_existing_fixture_is_deleted_first(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _stubs(tmp_path, monkeypatch)
    _workspace(tmp_path)
    stale = tmp_path / "dist/consumer-fixtures/rn-forge-ng-0.3.0/a-zone/stale.txt"
    stale.parent.mkdir(parents=True)
    stale.write_text("x")
    monkeypatch.chdir(tmp_path)
    assert cli.main(["consumer", "libs/ng"]) == 0
    assert not stale.exists()


def test_s9_4_5_5_a_workspace_range_in_the_installed_package_fails_the_cell(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    log = _stubs(tmp_path, monkeypatch)
    monkeypatch.setenv(
        "INSTALLED", json.dumps({"peerDependencies": {"@x/core": "workspace:^"}})
    )
    _workspace(tmp_path)
    monkeypatch.chdir(tmp_path)
    assert cli.main(["consumer", "libs/ng"]) == 1
    captured = capsys.readouterr()
    assert (
        '@rn-forge/ng peerDependencies["@x/core"] still uses workspace: protocol (workspace:^)'
        in captured.err
    )
    assert "consumer: 2 of 2 cells failed: a-zone, b-zoneless" in captured.out
    assert "node" not in log.read_text()


def test_s9_4_5_6_a_missing_tarball_fails_before_npm(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    log = _stubs(tmp_path, monkeypatch)
    _workspace(tmp_path, tarball=False)
    (tmp_path / "dist/tarballs/other.tgz").write_text("")
    monkeypatch.chdir(tmp_path)
    assert cli.main(["consumer", "libs/ng"]) == 1
    assert capsys.readouterr().err == (
        f"Expected packed tarball at {tmp_path}/dist/tarballs/rn-forge-ng-0.3.0.tgz"
        ' (found: other.tgz). Run "nx run ng:pack" first.\n'
    )
    assert not log.exists()


def test_s9_4_5_6_a_missing_tarball_directory_is_named(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    _stubs(tmp_path, monkeypatch)
    (tmp_path / "libs/ng").mkdir(parents=True)
    (tmp_path / "libs/ng/package.json").write_text(json.dumps(_library()))
    monkeypatch.chdir(tmp_path)
    assert cli.main(["consumer", "libs/ng"]) == 1
    assert "(found: (missing dir))" in capsys.readouterr().err


def test_s9_4_5_7_a_failing_cell_does_not_stop_the_others(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    log = _stubs(tmp_path, monkeypatch)
    monkeypatch.setenv("FAIL_CELL", "a-zone")
    _workspace(tmp_path)
    monkeypatch.chdir(tmp_path)
    assert cli.main(["consumer", "libs/ng"]) == 1
    assert "consumer: 1 of 2 cells failed: a-zone" in capsys.readouterr().out
    assert "node b-zoneless smoke.mjs" in log.read_text()


def test_s9_4_5_8_cell_runs_one_and_an_unknown_name_exits_2(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    log = _stubs(tmp_path, monkeypatch)
    _workspace(tmp_path)
    monkeypatch.chdir(tmp_path)
    assert cli.main(["consumer", "libs/ng", "--cell", "b-zoneless"]) == 0
    assert "consumer: 1 cells passed" in capsys.readouterr().out
    assert "a-zone" not in log.read_text()
    log.unlink()
    assert cli.main(["consumer", "libs/ng", "--cell", "nope"]) == 2
    assert "a-zone, b-zoneless" in capsys.readouterr().err
    assert not log.exists()
