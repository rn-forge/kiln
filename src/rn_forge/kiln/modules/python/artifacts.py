"""The artifacts `python` renders: kiln's block in `.importlinter`, and the packaged `cli.toml`."""

from __future__ import annotations

from rn_forge.commons.fs.blocks import ManagedBlock
from rn_forge.commons.fs.documents import ConfigFormat, DocumentUtils
from rn_forge.commons.generation import Artifact, ArtifactKind
from rn_forge.commons.generation.templated import TemplateArtifact, render_artifacts
from rn_forge.commons.text.templates import TemplateEngine

from rn_forge.kiln import __version__
from rn_forge.kiln.config import KilnConfig

__all__ = ["IMPORTLINTER_BLOCK", "render"]

IMPORTLINTER_BLOCK = ManagedBlock("rn-forge kiln")
"""kiln's fenced block in the repo's `.importlinter`."""


_FORBIDDEN_FRAMEWORKS = ("typer", "jinja2", "click", "django", "fastapi")


def render(config: KilnConfig) -> list[Artifact]:
    """Render `.importlinter` and, for a lifecycle repo, `cli.toml` for *config*; nothing for `node-lib`."""
    if config.is_node_lib:
        return []
    return [*_importlinter(config), *_cli_declaration(config)]


def _cli_declaration(config: KilnConfig) -> list[Artifact]:
    """The package's `cli.toml`: the config's `[cli]` and `[lifecycle]` tables."""
    if not config.lifecycle:
        return []
    tables = {
        key: value
        for key, value in (
            ("cli", config.document.cli),
            ("lifecycle", config.document.lifecycle),
        )
        if value is not None
    }
    header = (
        f"# Generated by kiln {__version__} from .rn-forge/kiln/config.toml"
        " — do not edit; run 'kiln apply'\n"
    )
    text = header + DocumentUtils.dumps(
        tables, ConfigFormat.TOML, multiline_arrays=True
    )
    path = "src/" + config.module.replace(".", "/") + "/cli.toml"
    return [Artifact(path, ArtifactKind.MANAGED, text)]


def _importlinter(config: KilnConfig) -> list[Artifact]:
    engine = TemplateEngine.cached(package="rn_forge.kiln.modules.python")
    workspace = config.is_workspace
    web = config.is_web
    if workspace:
        members = [config.module_for(package) for package in config.packages]
    elif web:
        members = [config.api_module]
    else:
        members = [config.module]
    forbidden = [m for m in _FORBIDDEN_FRAMEWORKS if m != config.backend]
    context: dict[str, object] = {
        "kiln_version": __version__,
        "workspace": workspace,
        "own_contracts": config.import_contracts == "own",
        "framework_edge": config.backend == "fastapi",
        "members_block": "\n".join(f"    {member}" for member in members),
        "forbidden_block": "\n".join(f"    {module}" for module in forbidden),
    }
    if not workspace:
        context["package"] = members[0]
    return render_artifacts(
        engine,
        context,
        [
            TemplateArtifact(
                ".importlinter",
                ArtifactKind.BLOCK,
                template="importlinter.j2",
                block=IMPORTLINTER_BLOCK,
            )
        ],
    )
