@pytest.mark.parametrize("name", ["node:format", "node:lint:format"])
def test_s16_7_3_5_overrides(tmp_path: Path, name: str) -> None:
    extra = f'\n[tasks]\n[tasks.command_overrides]\n"{name}" = "echo hi"\n'
    root = _root(tmp_path / "node", "node-lib")
    config = root / ".rn-forge/kiln/config.toml"
    config.write_text(config.read_text("utf-8") + extra, encoding="utf-8")
    key = name.removeprefix("node:")
    assert _node_tasks(root)["node"][key]["cmds"] == ["echo hi"]

    py = _root(tmp_path / "py", "python-tool")
    config = py / ".rn-forge/kiln/config.toml"
    config.write_text(config.read_text("utf-8") + extra, encoding="utf-8")
    with pytest.raises(AppException, match=name):
        TASKS.artifacts(KilnConfig.load(py), py)


def test_s16_7_3_6_the_scaffold_adds_prettier(tmp_path: Path) -> None:
    raw = tmp_path / "raw"
    raw.mkdir()
    with mock.patch("rn_forge.kiln.modules.node.angular.Process.execute") as run:
        scaffold_angular(raw)

    names = [c.args[0] for c in run.call_args_list]
    assert PRETTIER == "prettier@~3.9.10"
    assert names.index("coverage-v8") < names.index("prettier")
    assert names.index("prettier") < names.index("nx-install")
    call = run.call_args_list[names.index("prettier")]
    assert call.args == ("prettier", "pnpm", "add", "-D", PRETTIER)
    assert call.kwargs["cwd"] == str(raw / "workspace")


