HTTPS = "https://github.com/rn-forge/golden-lib"
NO_REMOTE = (
    "generate.no-remote: a published package needs the repository's GitHub "
    "remote: git remote add origin https://github.com/<owner>/<repo>"
)


def _new(parent: Path, name: str, archetype: str = "python-lib") -> Path:
    """`kiln new` into `parent/name`, staging beneath *parent*."""
    parent.mkdir(parents=True, exist_ok=True)
    with pytest.MonkeyPatch.context() as patch:
        patch.chdir(parent)
        commands.new(Path(name), archetype=archetype, docs="mkdocs", yes=True)
    return parent / name


def _git(root: Path, *args: str) -> str:
    done = subprocess.run(
        ["git", *args], cwd=root, check=True, capture_output=True, text=True
    )
    return done.stdout


def _lib(parent: Path, remote: str | None, name: str = "golden-lib") -> Path:
    root = _new(parent, name)
    _git(root, "init", "-q")
    if remote is not None:
        _git(root, "remote", "add", "origin", remote)
    return root


def _generate(root: Path, name: str) -> None:
    commands.generate_package(name, path=root)


def _tree(root: Path) -> dict[str, bytes]:
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file() and ".git" not in path.relative_to(root).parts[:1]
    }


def _toml(path: Path) -> dict[str, Any]:
    return tomllib.loads(path.read_text(encoding="utf-8"))


def _provenance(text: str) -> str:
    return re.sub(r"Generated by kiln \S+ from", "Generated by kiln X from", text)


def _is_subsequence(needle: list[str], haystack: list[str]) -> bool:
    remaining = iter(haystack)
    return all(line in remaining for line in needle)


def _site_description(text: str) -> str:
    return re.sub(
        r"^site_description: .*$", "site_description: X", text, count=1, flags=re.M
    )


@contextmanager
def _refused(code: str) -> Iterator[None]:
    """Expect an `AppException` whose message starts with *code*."""
    with pytest.raises(AppException) as raised:
        yield
    assert raised.value.message.startswith(f"{code}: ")


@pytest.fixture(autouse=True)
def _reset_console_mode() -> Iterator[None]:
    yield
    console.set_mode(OutputMode.PLAIN)


@pytest.fixture(scope="module")
def generated(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A `golden-lib` repository after `generate package` for both golden packages."""
    root = _lib(tmp_path_factory.mktemp("equality"), HTTPS)
    _generate(root, "golden-alpha")
    _generate(root, "golden-beta")
    return root


