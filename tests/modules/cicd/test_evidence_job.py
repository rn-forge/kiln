"""The `evidence` job, its task and the controls file it reads."""

from __future__ import annotations
import json
import pytest
import subprocess
from pathlib import Path
from rn_forge.commons.exceptions import AppException
from rn_forge.kiln.modules.cicd import controls
from rn_forge.kiln.modules.core import cycle
from tests.conftest import requires
from tests.modules.cicd.support import (
    ARCHETYPES,
    _ci_jobs,
    _ci_tasks_text_of,
    _rendered,
    _sonar_root,
)


EVIDENCE_ARCHETYPES = (*ARCHETYPES, "python-web-api", "python-web-app")
CONTROLS_PATH = ".rn-forge/kiln/security-controls.json"
EVIDENCE_IF = (
    "${{ !cancelled() && github.event_name == 'push' && "
    "github.ref == 'refs/heads/main' }}"
)


def _evidence_root(tmp_path: Path, archetype: str, on: bool, extra: str = "") -> Path:
    root = _sonar_root(tmp_path, archetype)
    if on:
        config = root / ".rn-forge" / "kiln" / "config.toml"
        config.write_text(
            config.read_text(encoding="utf-8")
            + f"\n[ci.checks]\nrelease-evidence = true\n{extra}",
            encoding="utf-8",
        )
    return root


def _tasks(root: Path) -> dict[str, object]:
    return _ci_tasks_text_of(root)["tasks"]  # type: ignore[return-value]


@pytest.mark.parametrize("archetype", [*EVIDENCE_ARCHETYPES, "node-lib"])
def test_evidence_is_off_by_default(tmp_path: Path, archetype: str) -> None:
    root = _evidence_root(tmp_path, archetype, False)
    assert "evidence" not in _ci_jobs(root)
    assert CONTROLS_PATH not in _rendered(root)
    assert "release:evidence" not in _tasks(root)


@pytest.mark.parametrize("archetype", EVIDENCE_ARCHETYPES)
def test_evidence_job_when_enabled(tmp_path: Path, archetype: str) -> None:
    job = _ci_jobs(_evidence_root(tmp_path, archetype, True))["evidence"]
    assert job["needs"] == ["release", "verify-release"]
    assert job["if"] == EVIDENCE_IF
    assert job["permissions"] == {
        "contents": "read",
        "actions": "read",
        "attestations": "read",
    }
    steps = job["steps"]
    assert [s["name"] for s in steps] == [  # type: ignore[index,union-attr]
        "Checkout",
        "Set up the toolchain",
        "Collect the security evidence",
        "Upload the security evidence",
    ]
    assert steps[2]["run"] == "task ci:release:evidence"  # type: ignore[index]
    assert steps[2]["env"] == {"GH_TOKEN": "${{ github.token }}"}  # type: ignore[index]
    assert steps[3]["with"] == {  # type: ignore[index]
        "name": "security-evidence",
        "path": "security-evidence.json",
    }


@pytest.mark.parametrize("archetype", EVIDENCE_ARCHETYPES)
def test_evidence_needs_a_release(tmp_path: Path, archetype: str) -> None:
    root = _evidence_root(tmp_path, archetype, True)
    config = root / ".rn-forge" / "kiln" / "config.toml"
    text = config.read_text(encoding="utf-8")
    config.write_text(
        text + '\n[ci]\nrelease = "none"\n'
        if "[ci]" not in text
        else text.replace('release = "tag-exists"', 'release = "none"'),
        encoding="utf-8",
    )
    with pytest.raises(AppException, match="release-evidence"):
        _rendered(root)


@pytest.mark.parametrize("archetype", EVIDENCE_ARCHETYPES)
def test_ci_ok_waits_for_evidence_only_when_enabled(
    tmp_path: Path, archetype: str
) -> None:
    on = _ci_jobs(_evidence_root(tmp_path / "on", archetype, True))
    assert "evidence" in on["ci-ok"]["needs"]  # type: ignore[operator]
    off = _ci_jobs(_evidence_root(tmp_path / "off", archetype, False))
    assert "evidence" not in off["ci-ok"]["needs"]  # type: ignore[operator]


def _manifest(root: Path) -> dict[str, object]:
    return json.loads(_rendered(root)[CONTROLS_PATH])


@pytest.mark.parametrize("archetype", EVIDENCE_ARCHETYPES)
def test_controls_file_lists_every_control(tmp_path: Path, archetype: str) -> None:
    manifest = _manifest(_evidence_root(tmp_path, archetype, True))
    assert str(manifest["generated"]).startswith("Generated by kiln")
    assert manifest["release"] == "tag-exists"
    rows = manifest["controls"]
    assert [r["name"] for r in rows] == [c.name for c in controls.CONTROLS]  # type: ignore[index,union-attr]
    for row in rows:  # type: ignore[union-attr]
        if row["source"] == "lint-job":
            assert (row["job"], row["step"]) == ("validate", "Validate")
        if row["name"] == "Secret scan":
            assert row["job"] == "secret-scan"


def test_controls_file_marks_scorecard_off_as_not_running(tmp_path: Path) -> None:
    def scorecard(path: Path, extra: str) -> object:
        rows = _manifest(_evidence_root(path, "python-tool", True, extra))["controls"]
        return next(r for r in rows if r["name"] == "Scorecard")["runs"]  # type: ignore[index,union-attr]

    assert scorecard(tmp_path / "off", "") is False
    assert scorecard(tmp_path / "on", "scorecard = true\n") is True


@pytest.mark.parametrize("archetype", EVIDENCE_ARCHETYPES)
def test_lint_step_is_the_validate_jobs_step(tmp_path: Path, archetype: str) -> None:
    jobs = _ci_jobs(_evidence_root(tmp_path, archetype, True))
    steps = jobs[controls.LINT_JOB]["steps"]
    assert controls.LINT_STEP in [s.get("name") for s in steps]  # type: ignore[union-attr]


def test_release_evidence_task_runs_the_collector(tmp_path: Path) -> None:
    task = _tasks(_evidence_root(tmp_path, "python-tool", True))["release:evidence"]
    (cmd,) = task["cmds"]  # type: ignore[index]
    assert "evidence collect" in cmd
    assert "--controls .rn-forge/kiln/security-controls.json" in cmd
    assert '>> "$GITHUB_STEP_SUMMARY"' in cmd


@pytest.mark.parametrize("archetype", ["python-lib", "python-tool"])
@requires("zizmor", "actionlint")
def test_actionlint_and_zizmor_accept_the_evidence_job(
    tmp_path: Path, archetype: str
) -> None:
    root = _evidence_root(tmp_path, archetype, True)
    cycle.apply(root, home=tmp_path / "home")
    for command in (
        ["zizmor", "--offline", str(root / ".github")],
        ["actionlint", ".github/workflows/ci.yml"],
    ):
        result = subprocess.run(
            command, cwd=root, capture_output=True, text=True, check=False
        )
        assert result.returncode == 0, result.stdout + result.stderr
