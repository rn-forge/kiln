ARCHETYPES = ("python-app", "python-tool", "python-lib")


def _root(
    tmp_path: Path,
    archetype: str = "python-tool",
    profile: str = "mkdocs",
    extra: str = "",
) -> Path:
    return write_config(
        tmp_path,
        archetype,
        name="demo",
        docs=profile,
        packages=LIB_PACKAGES if archetype == "python-lib" else None,
        docs_extra=extra,
    )


def _codes(root: Path) -> list[str]:
    return sorted(f.code for f in module_findings("tasks", KilnConfig.load(root), root))


def _run_task(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    # The generated CI sets KILN_DOCTOR_FULL on push and dispatch; a test asks
    # for it explicitly, never inherits it.
    env = {k: v for k, v in os.environ.items() if k != "KILN_DOCTOR_FULL"}
    return subprocess.run(
        ["task", *args], cwd=root, capture_output=True, text=True, check=False, env=env
    )


def _normalized(text: str) -> str:
    """Drop the provenance line's kiln version, the only line that never matches."""
    return re.sub(
        r"^# Generated by kiln .*$",
        "# Generated by kiln X",
        text,
        count=1,
        flags=re.M,
    )


STEP = "workspace:step"


def _unmarked(cmds: list[dict]) -> list[dict]:
    return [c for c in cmds if c["task"] != STEP]


WEB_CONFIG = """
schema_version = 1

[repository]
name = "demo"
owner = "rn-forge"
archetype = "{archetype}"

[docs]
profile = "none"

[archetype."{archetype}"]
backend = "{backend}"
{extra}
"""


def _web_root(tmp_path: Path, archetype: str, backend: str, extra: str = "") -> Path:
    config = tmp_path / ".rn-forge" / "kiln" / "config.toml"
    config.parent.mkdir(parents=True)
    config.write_text(
        WEB_CONFIG.format(archetype=archetype, backend=backend, extra=extra),
        encoding="utf-8",
    )
    return tmp_path


def _ci_tasks(root: Path) -> dict[str, object]:
    rendered = {a.path: a.content for a in TASKS.artifacts(KilnConfig.load(root), root)}
    return YamlUtils.load(rendered["tasks/ci.yml"])


def _root_vars(root: Path) -> dict[str, str]:
    """The root Taskfile's `vars:`, which every included file inherits."""
    rendered = {a.path: a.content for a in TASKS.artifacts(KilnConfig.load(root), root)}
    return YamlUtils.load(rendered["Taskfile.yml"])["vars"]


