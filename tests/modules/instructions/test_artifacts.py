"""S4.3.5 — the `instructions` module's artifacts: the kiln block, and `standard.md`.

Also proves the five properties every F4.3 story owes its module
(`docs/specs/epics/E4-generator/F4.3-concern-modules.md`).
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from rn_forge.tooling.generation import Action, ArtifactKind

from rn_forge.kiln.config import KilnConfig
from rn_forge.kiln.modules.core import cycle
from rn_forge.kiln.modules.docs import DOCS
from rn_forge.kiln.modules.docs.scaffold import scaffold as docs_scaffold
from rn_forge.kiln.modules.instructions import INSTRUCTIONS
from rn_forge.kiln.modules.instructions.artifacts import KILN_BLOCK
from rn_forge.kiln.modules.instructions.scaffold import scaffold

GOLDEN = Path(__file__).resolve().parents[2] / "fixtures" / "golden"
ARCHETYPES = ("python-app", "python-tool", "python-lib")

BLOCK_KEY = "CLAUDE.md#rn-forge kiln"
STANDARD = ".rn-forge/kiln/standard.md"

CONFIG = """
schema_version = 1

[repository]
name = "demo"
archetype = "{archetype}"

[docs]
profile = "{profile}"
{docs_extra}
[ci]
sonar = {sonar}
"""

PACKAGES = """
[archetype."python-lib"]
packages = ["packages/alpha", "packages/beta"]
"""


def _write_config(
    root: Path,
    archetype: str = "python-tool",
    profile: str = "mkdocs",
    sonar: bool = True,
    docs_extra: str = "",
) -> None:
    config = root / ".rn-forge" / "kiln" / "config.toml"
    config.parent.mkdir(parents=True, exist_ok=True)
    text = CONFIG.format(
        archetype=archetype,
        profile=profile,
        sonar=str(sonar).lower(),
        docs_extra=docs_extra,
    )
    if archetype == "python-lib":
        text += PACKAGES
    config.write_text(text, encoding="utf-8")


def _root(tmp_path: Path, archetype: str = "python-tool", **kwargs: object) -> Path:
    _write_config(tmp_path, archetype, **kwargs)  # type: ignore[arg-type]
    return tmp_path


def _new(tmp_path: Path, archetype: str = "python-tool", **kwargs: object) -> Path:
    """Scaffold and apply into an empty directory, as `kiln new` will."""
    root = _root(tmp_path, archetype, **kwargs)
    config = KilnConfig.load(root)
    scaffold(root, config)
    docs_scaffold(root, config)
    cycle.apply(root, home=tmp_path / "home")
    return root


def _rendered(root: Path) -> dict[str, str]:
    return {
        a.key: a.content for a in INSTRUCTIONS.artifacts(KilnConfig.load(root), root)
    }


def _actions(root: Path, tmp_path: Path) -> dict[str, Action]:
    return {
        change.key: change.action
        for change in cycle.plan(root, home=tmp_path / "home").changes
    }


def _snapshot(root: Path) -> dict[str, bytes]:
    return {
        str(path.relative_to(root)): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
        and ".rn-forge/kiln/backups" not in path.as_posix()
        and ".rn-forge/kiln/rendered" not in path.as_posix()
    }


@pytest.mark.parametrize("archetype", ARCHETYPES)
def test_s4_3_5_property1_renders_exactly_the_module_s_template_inventory_rows(
    tmp_path: Path, archetype: str
) -> None:
    root = _root(tmp_path, archetype)
    artifacts = INSTRUCTIONS.artifacts(KilnConfig.load(root), root)
    assert [(a.key, a.kind) for a in artifacts] == [
        (BLOCK_KEY, ArtifactKind.BLOCK),
        (STANDARD, ArtifactKind.MANAGED),
    ]
    assert artifacts[0].block == KILN_BLOCK


@pytest.mark.parametrize("archetype", ARCHETYPES)
def test_s4_3_5_property2_into_an_empty_directory_only_inserts_and_creates(
    tmp_path: Path, archetype: str
) -> None:
    actions = _actions(_root(tmp_path, archetype), tmp_path)
    assert actions[BLOCK_KEY] is Action.INSERT
    assert actions[STANDARD] is Action.CREATE


@pytest.mark.parametrize("archetype", ARCHETYPES)
def test_s4_3_5_property3_a_second_apply_is_unchanged(
    tmp_path: Path, archetype: str
) -> None:
    root = _new(tmp_path, archetype)
    actions = _actions(root, tmp_path)
    assert actions[BLOCK_KEY] is Action.UNCHANGED
    assert actions[STANDARD] is Action.UNCHANGED


def _normalized(text: str) -> str:
    """Drop the provenance line's kiln version, the only line that never matches."""
    return re.sub(r"Generated by kiln \S+ from", "Generated by kiln X from", text)


@pytest.mark.parametrize("archetype", ARCHETYPES)
def test_s4_3_5_property4_matches_its_golden(tmp_path: Path, archetype: str) -> None:
    golden = GOLDEN / archetype
    config = KilnConfig.load(golden)
    rendered = _rendered(golden)
    claude = (golden / "CLAUDE.md").read_text(encoding="utf-8")

    assert _normalized(rendered[BLOCK_KEY]) == _normalized(
        KILN_BLOCK.extract(claude) or ""
    )
    assert _normalized(rendered[STANDARD]) == _normalized(
        (golden / STANDARD).read_text(encoding="utf-8")
    )

    scaffold(tmp_path, config)
    body = (tmp_path / "CLAUDE.md").read_text(encoding="utf-8")
    assert _normalized(KILN_BLOCK.render(body, rendered[BLOCK_KEY])) == _normalized(
        claude
    )
    assert (tmp_path / "AGENTS.md").read_text(encoding="utf-8") == (
        golden / "AGENTS.md"
    ).read_text(encoding="utf-8")


