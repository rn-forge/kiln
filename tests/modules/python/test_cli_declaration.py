"""The `python` module renders the packaged CLI declaration."""

from __future__ import annotations

import tomllib
from pathlib import Path

from tests.conftest import write_config
from rn_forge.commons.generation import Artifact, ArtifactKind

from rn_forge.kiln.config import KilnConfig
from rn_forge.kiln.modules.python import artifacts

ROOT = Path(__file__).resolve().parents[3]

TAIL = """
[cli]
name = "python-tool"
help = "A tool."

[lifecycle]
verbs = ["version"]
"""


def _declarations(config: KilnConfig) -> list[Artifact]:
    return [a for a in artifacts.render(config) if a.path.endswith("/cli.toml")]


def test_a_lifecycle_repository_gets_a_packaged_cli_declaration(
    tmp_path: Path,
) -> None:
    config = KilnConfig.load(
        write_config(tmp_path, "python-tool", name="python-tool", tail=TAIL)
    )

    [declaration] = _declarations(config)

    assert declaration.path == "src/python_tool/cli.toml"
    assert declaration.kind is ArtifactKind.MANAGED
    assert declaration.content.startswith("# Generated by kiln")
    parsed = tomllib.loads(declaration.content)
    assert parsed["cli"] == config.document.cli
    assert parsed["lifecycle"] == config.document.lifecycle


def test_a_repository_without_lifecycle_gets_none(tmp_path: Path) -> None:
    config = KilnConfig.load(write_config(tmp_path, "python-app", name="demo"))

    assert _declarations(config) == []


def test_kilns_own_cli_declaration_is_rendered() -> None:
    config = KilnConfig.load(ROOT)

    [declaration] = _declarations(config)

    assert declaration.path == "src/rn_forge/kiln/cli.toml"
    assert (ROOT / declaration.path).read_text(encoding="utf-8") == declaration.content
