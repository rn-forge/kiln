"""Reusable stage workflows (S15.8.9)."""

from __future__ import annotations

import importlib.util
from pathlib import Path
from typing import Any

import pytest

from rn_forge.commons.fs.documents import YamlUtils
from rn_forge.kiln.config import KilnConfig
from rn_forge.kiln.modules.cicd import CICD
from rn_forge.kiln.modules.cicd.checks import entrypoint, hooks, pins

_spec = importlib.util.spec_from_file_location(
    "cicd_workflows", Path(__file__).with_name("workflows.py")
)
assert _spec is not None and _spec.loader is not None
workflows = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(workflows)

CONFIG = """
schema_version = 1

[repository]
name = "demo"
owner = "rn-forge"
archetype = "{archetype}"

[docs]
profile = "mkdocs"

[ci]
provider = "github"
sonar = true
release = "{release}"
"""

PACKAGES = """
[archetype."python-lib"]
packages = ["packages/alpha", "packages/beta"]
"""

ALL_ARCHETYPES = (
    "python-tool",
    "python-app",
    "python-web-api",
    "python-web-app",
    "python-lib",
    "node-lib",
)
STAGES = ("integration", "smoke", "sonar", "release", "verify-release", "docs")
INLINE = (
    "validate",
    "plan",
    "test",
    "suites",
    "dependency-review",
    "secret-scan",
    "checks-ok",
    "ci-ok",
)
INLINE_PYTHON_LIB = ("release",)
CI_YML = ".github/workflows/ci.yml"
HEADER = "# Generated by kiln "
SONAR_IF = (
    "${{ !cancelled() && !contains(needs.*.result, 'failure') "
    "&& github.actor != 'dependabot[bot]' "
    "&& ((github.event_name == 'pull_request' "
    "&& github.event.pull_request.head.repo.full_name == github.repository) "
    "|| (github.event_name != 'pull_request' "
    "&& github.ref == 'refs/heads/main')) }}"
)


def _render(tmp_path: Path, archetype: str) -> tuple[Path, dict[str, str]]:
    root = tmp_path / archetype
    config = root / ".rn-forge" / "kiln" / "config.toml"
    config.parent.mkdir(parents=True, exist_ok=True)
    release = {"python-lib": "pypi", "node-lib": "nx-dispatch"}.get(
        archetype, "tag-exists"
    )
    text = CONFIG.format(archetype=archetype, release=release)
    if archetype == "python-lib":
        text += PACKAGES
    elif archetype in {"python-web-api", "python-web-app"}:
        text += f'\n[archetype."{archetype}"]\n'
        if archetype == "python-web-app":
            text += 'frontend = "angular"\n'
    config.write_text(text, encoding="utf-8")
    loaded = KilnConfig.load(root)
    return root, {a.path: a.content for a in CICD.artifacts(loaded, root)}


def _raw_jobs(files: dict[str, str]) -> dict[str, dict[str, Any]]:
    return YamlUtils.load(files[CI_YML])["jobs"]


def _expected(archetype: str) -> list[str]:
    return [
        s
        for s in STAGES
        if not (s == "integration" and archetype == "node-lib")
        and not (s == "release" and archetype == "python-lib")
    ]


@pytest.mark.parametrize("archetype", ALL_ARCHETYPES)
def test_s15_8_9_1_files(tmp_path: Path, archetype: str) -> None:
    _, files = _render(tmp_path, archetype)
    rendered = sorted(
        p.rsplit("/_", 1)[1].removesuffix(".yml")
        for p in files
        if p.startswith(".github/workflows/_")
    )
    assert rendered == sorted(_expected(archetype))
    for stage in rendered:
        text = files[f".github/workflows/_{stage}.yml"]
        assert text.startswith(HEADER)
        assert list(YamlUtils.load(text)["on"]) == ["workflow_call"]


@pytest.mark.parametrize("archetype", ALL_ARCHETYPES)
def test_s15_8_9_2_callers(tmp_path: Path, archetype: str) -> None:
    _, files = _render(tmp_path, archetype)
    jobs = _raw_jobs(files)
    for stage in _expected(archetype):
        caller = jobs[stage]
        assert caller["uses"] == f"./.github/workflows/_{stage}.yml"
        assert caller["needs"]
        assert caller["if"]
        assert caller["permissions"]
        called = YamlUtils.load(files[f".github/workflows/_{stage}.yml"])["jobs"]
        assert all("needs" not in j and "if" not in j for j in called.values())
    assert "secrets: inherit" not in files[CI_YML]
    if "sonar" in jobs:
        assert jobs["sonar"]["secrets"] == {"SONAR_TOKEN": "${{ secrets.SONAR_TOKEN }}"}
        assert jobs["sonar"]["if"] == SONAR_IF
    if archetype != "node-lib":
        for stage in ("integration", "smoke"):
            assert jobs[stage]["with"] == {
                "matrix": f"${{{{ needs.plan.outputs.{stage} }}}}"
            }
    if "verify-release" in jobs and archetype != "python-lib":
        assert jobs["verify-release"]["with"] == {
            "tag": "${{ needs.release.outputs.tag }}"
        }


@pytest.mark.parametrize("archetype", ALL_ARCHETYPES)
def test_s15_8_9_3_stay_inline(tmp_path: Path, archetype: str) -> None:
    _, files = _render(tmp_path, archetype)
    jobs = _raw_jobs(files)
    inline = INLINE + (INLINE_PYTHON_LIB if archetype == "python-lib" else ())
    for name in inline:
        if name in jobs:
            assert "uses" not in jobs[name], name
    assert {"validate", "checks-ok", "ci-ok"} <= set(jobs)


@pytest.mark.parametrize("archetype", ALL_ARCHETYPES)
def test_s15_8_9_4_same_jobs(tmp_path: Path, archetype: str) -> None:
    _, files = _render(tmp_path, archetype)
    raw = _raw_jobs(files)
    merged = workflows.jobs(files)
    assert list(merged) == list(raw)
    for stage in _expected(archetype):
        job = merged[stage]
        assert {"uses", "with", "secrets"}.isdisjoint(job), stage
        assert job["runs-on"] == "ubuntu-latest"
        assert job["steps"]
        assert job["needs"] == raw[stage]["needs"]
        text = str(job)
        for name in ("matrix", "tag", "release-order"):
            assert f"inputs.{name}" not in text, stage


@pytest.mark.parametrize("archetype", ALL_ARCHETYPES)
def test_s15_8_9_5_gates_need_callers(tmp_path: Path, archetype: str) -> None:
    _, files = _render(tmp_path, archetype)
    raw = _raw_jobs(files)
    for gate in ("checks-ok", "ci-ok"):
        assert raw[gate]["needs"]
        assert set(raw[gate]["needs"]) <= set(raw), gate
    assert {"smoke"} <= set(raw["checks-ok"]["needs"])
    assert {"release", "verify-release", "docs"} <= set(raw["ci-ok"]["needs"])


@pytest.mark.parametrize("archetype", ALL_ARCHETYPES)
def test_s15_8_9_6_declared_job_cannot_take_the_name(
    tmp_path: Path, archetype: str
) -> None:
    root, files = _render(tmp_path, archetype)
    for path, content in files.items():
        if path.startswith(".github/workflows/"):
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    config = KilnConfig.load(root)
    for check in (pins, entrypoint, hooks):
        assert check.check(config, root) == [], check.__name__

    config_file = root / ".rn-forge" / "kiln" / "config.toml"
    declared = "".join(
        f'\n[[ci.jobs]]\nname = "x-{stage}"\nuses = "./.github/workflows/_{stage}.yml"\n'
        for stage in STAGES
    )
    config_file.write_text(
        config_file.read_text(encoding="utf-8") + declared, encoding="utf-8"
    )
    findings = hooks.check(KilnConfig.load(root), root)
    assert [f.code for f in findings] == ["ci.hook-reserved"] * len(STAGES)
