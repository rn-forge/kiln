def _commit(repo: Path, *files: str) -> str:
    for name in files:
        path = repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(path.read_text() + "x\n" if path.exists() else "x\n")
    git(repo, "add", "-A")
    git(repo, "commit", "-m", "c")
    return git(repo, "rev-parse", "HEAD")


