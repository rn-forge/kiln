def test_s11_3_1_5_a_repeated_name_fails_with_package_exists_and_writes_nothing(
    generated: Path, tmp_path: Path
) -> None:
    root = tmp_path / "copy"
    shutil.copytree(generated, root, symlinks=True)
    tree = _tree(root)
    with _refused("generate.package-exists"):
        _generate(root, "golden-alpha")
    assert _tree(root) == tree


